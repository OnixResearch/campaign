/// The selected classes.
///
/// # Errors
///
/// Returns `Diverged` for a pinned code that names no declared class.
pub(in crate::catalog::evidence) fn selected()
-> crate::verdicts::ConformanceResult<alloc::vec::Vec<super::features::StateClass>> {
    TABLE
        .iter()
        .map(|code| {
            super::features::StateClass::of_code(*code)
                .filter(|class| super::classes::admits(*class))
                .ok_or(crate::verdicts::ConformanceError::Diverged {
                    expected: "every pinned class is a declared class",
                })
        })
        .collect()
}
